@app.get("/incidents")
def get_incidents():

    connection = sqlite3.connect(DATABASE)

    cursor = connection.cursor()


    cursor.execute("""
        SELECT id,
               event,
               risk_score,
               risk_level,
               timestamp

        FROM incidents

        ORDER BY id DESC
    """)


    rows = cursor.fetchall()

    connection.close()


    incidents = []


    for row in rows:

        incidents.append({

            "id": row[0],

            "event": row[1],

            "risk_score": row[2],

            "risk_level": row[3],

            "timestamp": row[4]

        })


    return {

        "status": "success",

        "incidents": incidents

    }


