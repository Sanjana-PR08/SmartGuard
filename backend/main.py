# EMAIL ALERT FUNCTION - BREVO
# ============================================================

def send_email_alert(event, result):

    """
    Sends an automatic SmartGuard security alert
    through Brevo when the risk becomes SUSPICIOUS
    or HIGH RISK.
    """

    # --------------------------------------------------------
    # Only send email for suspicious or high-risk events
    # --------------------------------------------------------

    if result["risk_level"] == "NORMAL":
      return


    # --------------------------------------------------------
    # Check Brevo configuration
    # --------------------------------------------------------

    if not BREVO_API_KEY:
        print("EMAIL ERROR: BREVO_API_KEY is missing.")
        return

    if not BREVO_SENDER_EMAIL:
        print("EMAIL ERROR: BREVO_SENDER_EMAIL is missing.")
        return

    if not ALERT_EMAIL:
        print("EMAIL ERROR: ALERT_EMAIL is missing.")
        return


    # --------------------------------------------------------
    # Current time
    # --------------------------------------------------------

    current_time = datetime.now().strftime(
        "%Y-%m-%d %H:%M:%S"
    )


    # --------------------------------------------------------
    # Risk information
    # --------------------------------------------------------

    risk_score = result["risk_score"]

    risk_level = result["risk_level"]

    reasons = result.get("reasons", [])


    reasons_html = ""

    for reason in reasons:

        reasons_html += f"""
        <li>{reason}</li>
        """


    # --------------------------------------------------------
    # Email subject
    # --------------------------------------------------------

    subject = f"SmartGuard Alert - {risk_level}"


    # --------------------------------------------------------
    # Email body
    # --------------------------------------------------------

    html_content = f"""
    <html>

    <body style="font-family: Arial, sans-serif;">

        <h2>SmartGuard Security Alert</h2>

        <p>
            A security event has been detected by the
            SmartGuard system.
        </p>

        <hr>

        <h3>Security Details</h3>

        <p>
            <b>Event:</b> {event}
        </p>

        <p>
            <b>Risk Score:</b> {risk_score}/100
        </p>

        <p>
            <b>Risk Level:</b> {risk_level}
        </p>

        <p>
            <b>Time:</b> {current_time}
        </p>

        <h3>Reasons</h3>

        <ul>
            {reasons_html}
        </ul>

        <hr>

        <p>
            This alert was automatically generated by
            the SmartGuard Cyber-Physical Security System.
        </p>

    </body>

    </html>
    """


    # --------------------------------------------------------
    # Brevo API request
    # --------------------------------------------------------

    url = "https://api.brevo.com/v3/smtp/email"


    headers = {
        "accept": "application/json",
        "api-key": BREVO_API_KEY,
        "content-type": "application/json"
    }


    payload = {

        "sender": {
            "name": "SmartGuard",
            "email": BREVO_SENDER_EMAIL
        },

        "to": [
            {
                "email": ALERT_EMAIL
            }
        ],

        "subject": subject,

        "htmlContent": html_content
    }


    # --------------------------------------------------------
    # Send email
    # --------------------------------------------------------

    try:

        response = requests.post(
            url,
            headers=headers,
            json=payload,
            timeout=10
        )


        if response.status_code in [200, 201]:

            print(
                f"EMAIL SENT: {risk_level} alert sent successfully."
            )

        else:

            print(
                "EMAIL ERROR:",
                response.status_code,
                response.text
            )


    except requests.exceptions.RequestException as error:

        print(
            "EMAIL CONNECTION ERROR:",
            error
        )


