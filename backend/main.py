@app.delete("/delete-history")
def delete_history():

    connection = sqlite3.connect(DATABASE)

    cursor = connection.cursor()


    cursor.execute(
        "DELETE FROM incidents"
    )


    cursor.execute(
        "DELETE FROM sqlite_sequence "
        "WHERE name='incidents'"
    )


    connection.commit()

    connection.close()


    return {

        "status": "success",

        "message":
        "Incident history deleted and "
        "ID numbering reset"

    }


