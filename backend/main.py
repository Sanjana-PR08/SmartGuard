@app.post("/rfid")
def rfid_authentication(card_id: str):

    global active_events

    global vibration_count

    global unknown_rfid_count


    current_time = datetime.now().strftime(
        "%Y-%m-%d %H:%M:%S"
    )


    # ========================================================
    # AUTHORIZED RFID
    # ========================================================

    if card_id == "authorized_rfid":

        active_events = []


        return {

            "status": "success",

            "authorized": True,

            "message": "RFID Authorized",

            "user": "Authorized User",

            "card_id": card_id,

            "timestamp": current_time

        }


    # ========================================================
    # UNKNOWN RFID
    # ========================================================

    if card_id == "unknown_rfid":

        unknown_rfid_count += 1


        if card_id not in active_events:

            active_events.append(card_id)


        # ----------------------------------------------------
        # 4 OR MORE UNAUTHORIZED ATTEMPTS
        # ----------------------------------------------------

        if unknown_rfid_count >= 4:

            result = {

                "risk_score": 100,

                "risk_level": "HIGH RISK",

                "reasons": [

                    f"Repeated unauthorized RFID attempts "
                    f"({unknown_rfid_count} times)"

                ]

            }


            message = (
                "HIGH RISK: Repeated unauthorized "
                "access attempts detected!"
            )


        # ----------------------------------------------------
        # 2 OR 3 UNAUTHORIZED ATTEMPTS
        # ----------------------------------------------------

        elif unknown_rfid_count >= 2:

            result = {

                "risk_score": 50,

                "risk_level": "SUSPICIOUS",

                "reasons": [

                    f"Multiple unauthorized RFID attempts "
                    f"({unknown_rfid_count} times)"

                ]

            }


            message = (
                "SUSPICIOUS: Multiple unauthorized "
                "access attempts detected!"
            )


        # ----------------------------------------------------
        # FIRST UNAUTHORIZED ATTEMPT
        # ----------------------------------------------------

        else:

            result = {

                "risk_score": 20,

                "risk_level": "NORMAL",

                "reasons": [

                    "Unknown RFID detected"

                ]

            }


            message = "WARNING: Unknown RFID detected!"


    # ========================================================
    # HIGH VIBRATION
    # ========================================================

    elif card_id == "high_vibration":

        vibration_count += 1


        if card_id not in active_events:

            active_events.append(card_id)


        # ----------------------------------------------------
        # UNAUTHORIZED RFID + VIBRATION
        # ----------------------------------------------------

        if unknown_rfid_count >= 2:

            result = {

                "risk_score": 100,

                "risk_level": "HIGH RISK",

                "reasons": [

                    f"Unauthorized RFID attempts: "
                    f"{unknown_rfid_count}",

                    f"Vibration detected: "
                    f"{vibration_count}"

                ]

            }


            message = (
                "HIGH RISK: Unauthorized access followed "
                "by vibration detected!"
            )


        # ----------------------------------------------------
        # REPEATED VIBRATION
        # ----------------------------------------------------

        elif vibration_count > 3:

            result = {

                "risk_score": 100,

                "risk_level": "HIGH RISK",

                "reasons": [

                    f"Repeated vibration detected "
                    f"({vibration_count} times)"

                ]

            }


            message = (
                "HIGH RISK: Repeated vibration detected!"
            )


        # ----------------------------------------------------
        # NORMAL VIBRATION EVENT
        # ----------------------------------------------------

        else:

            result = calculate_risk(
                active_events
            )

            message = "Vibration event detected"


    # ========================================================
    # OTHER SECURITY EVENTS
    # ========================================================

    elif card_id in [

        "door_forced",

        "unusual_access_time",

        "sensor_disconnection"

    ]:

        if card_id not in active_events:

            active_events.append(card_id)


        result = calculate_risk(
            active_events
        )


        message = (
            f"Security event detected: {card_id}"
        )


    # ========================================================
    # UNKNOWN EVENT
    # ========================================================

    else:

        return {

            "status": "error",

            "message": "Unknown event",

            "event": card_id

        }


    # ========================================================
    # SAVE INCIDENT TO DATABASE
    # ========================================================

    connection = sqlite3.connect(DATABASE)

    cursor = connection.cursor()


    cursor.execute("""
        INSERT INTO incidents
        (event, risk_score, risk_level, timestamp)
        VALUES (?, ?, ?, ?)
    """, (

        card_id,

        result["risk_score"],

        result["risk_level"],

        current_time

    ))


    connection.commit()

    connection.close()


    # ========================================================
    # SEND EMAIL ALERT
    # ========================================================

    send_email_alert(

        card_id,

        result

    )


    # ========================================================
    # TERMINAL LOG
    # ========================================================

    print(

        f"EVENT={card_id} | "

        f"UNAUTHORIZED_COUNT="
        f"{unknown_rfid_count} | "

        f"VIBRATION_COUNT="
        f"{vibration_count} | "

        f"RISK="
        f"{result['risk_score']} | "

        f"LEVEL="
        f"{result['risk_level']}"

    )


    # ========================================================
    # RESPONSE
    # ========================================================

    return {

        "status": "success",

        "event": card_id,

        "message": message,

        "timestamp": current_time,

        "active_events": active_events,

        "security_analysis": result

    }


