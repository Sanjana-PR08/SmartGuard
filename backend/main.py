@app.post("/risk")
def check_risk(event: SecurityEvent):

    result = calculate_risk(event.all_events)


    current_time = datetime.now().strftime(
        "%Y-%m-%d %H:%M:%S"
    )


    # --------------------------------------------------------
    # Save incident
    # --------------------------------------------------------

    connection = sqlite3.connect(DATABASE)

    cursor = connection.cursor()

    cursor.execute("""
        INSERT INTO incidents
        (event, risk_score, risk_level, timestamp)
        VALUES (?, ?, ?, ?)
    """, (
        event.event,
        result["risk_score"],
        result["risk_level"],
        current_time
    ))

    connection.commit()

    connection.close()


    # --------------------------------------------------------
    # Send email if suspicious/high risk
    # --------------------------------------------------------

    send_email_alert(
        event.event,
        result
    )


    return {

        "status": "success",

        "security_analysis": result

    }


